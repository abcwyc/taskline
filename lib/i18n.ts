export function translate(locale: AppLocale, key: string): string {
   return locale === 'zh-CN' ? (ZH_CN[key] ?? key) : key;
}

/**
 * Module-level locale for code outside the React tree (zustand stores, toasts,
 * utils). Kept in sync by LanguageProvider.
 */
let currentLocale: AppLocale = 'en';

export function setI18nLocale(locale: AppLocale) {
   currentLocale = locale;
}

export function getI18nLocale(): AppLocale {
   return currentLocale;
}

/** Translate using the module-level locale — for code that cannot call useLanguage(). */
export function tt(key: string): string {
   return translate(currentLocale, key);
}

/* Chinese equivalents for the date patterns used across the app. */
const ZH_DATE_PATTERNS: Record<string, string> = {
   'MMM d': 'M月d日',
   'MMM d, yyyy': 'yyyy年M月d日',
   'MMM yyyy': 'yyyy年M月',
   'EEEE, MMM d': 'M月d日 EEEE',
};

/** Locale-aware date formatting: English patterns for en, natural Chinese for zh-CN. */
export function formatAppDate(
   locale: AppLocale,
   date: Date | number | string,
   enPattern: string,
   zhPattern?: string
): string {
   const d = typeof date === 'string' ? new Date(date) : date;
   if (locale === 'zh-CN') {
      return formatDateFns(d, zhPattern ?? ZH_DATE_PATTERNS[enPattern] ?? enPattern, {
         locale: zhCN,
      });
   }
   return formatDateFns(d, enPattern);
}

const ZH_TIME_UNITS: Record<string, string> = {
   second: '秒',
   minute: '分钟',
   hour: '小时',
   day: '天',
   week: '周',
   month: '个月',
   year: '年',
};

/**
 * Localize English relative-time strings produced by the API
 * ("2h ago", "5 minutes ago", "just now", "in 3 days") into Chinese.
 * Unknown formats are returned unchanged.
 */
export function formatRelativeTime(locale: AppLocale, text: string): string {
   if (locale !== 'zh-CN') return text;
   const trimmed = text.trim();
   if (/^(just now|now)$/i.test(trimmed)) return '刚刚';
   const ago = trimmed.match(/^(\d+)\s*(mo|s|m|h|d|w|y)(?:ec|in|our|ay|eek)?s?\s*ago$/i);
   if (ago) {
      const unitMap: Record<string, string> = {
         s: '秒',
         m: '分钟',
         h: '小时',
         d: '天',
         w: '周',
         mo: '个月',
         y: '年',
      };
      return `${ago[1]}${unitMap[ago[2].toLowerCase()]}前`;
   }
   const full = trimmed.match(
      /^(\d+)\s+(second|minute|hour|day|week|month|year)s?(?:\s+(?:ago|before))?$/i
   );
   if (full) return `${full[1]}${ZH_TIME_UNITS[full[2].toLowerCase()]}前`;
   const future = trimmed.match(/^in\s+(\d+)\s+(second|minute|hour|day|week|month|year)s?$/i);
   if (future) return `${future[1]}${ZH_TIME_UNITS[future[2].toLowerCase()]}后`;
   return text;
}

export function browserLocale(languages: readonly string[] = []): AppLocale {
   return languages.some((language) => language.toLowerCase().startsWith('zh')) ? 'zh-CN' : 'en';
}
